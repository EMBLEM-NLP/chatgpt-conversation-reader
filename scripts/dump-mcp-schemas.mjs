#!/usr/bin/env node
/**
 * Writes docs/mcp-tool-schemas.json: the MCP tool schemas of the GCR server (CODEX_TASK deliverable C, "MCP schemas").
 *
 * The file is not hand-written. This script builds the REAL server in memory from the compiled output, connects the real
 * SDK client to it over an in-memory transport and records exactly what `tools/list` returns (name, title, description,
 * inputSchema, outputSchema, annotations), plus the facts of the `initialize` result a client sees (server name/version,
 * capabilities, instructions) and the alias table. Nothing is read from a database or the network; the in-memory database
 * is created and discarded.
 *
 * Deterministic: object keys are sorted recursively, arrays keep their meaningful order (tools in registration order,
 * enums as declared), output is pretty-printed with a trailing newline, no timestamps. The server is built with fixed
 * options so neither the environment (GCR_MCP_MAX_RESULT_BYTES ...) nor the working directory changes the result.
 *
 * Usage:
 *   node scripts/dump-mcp-schemas.mjs                    write docs/mcp-tool-schemas.json from ./dist (run `npm run build` first)
 *   node scripts/dump-mcp-schemas.mjs --check            exit 1 when the committed file is stale (for CI)
 *   node scripts/dump-mcp-schemas.mjs --dist <dir>       read the compiled modules from <dir> (it holds mcp/server.js, sdk/gcr.js)
 *   node scripts/dump-mcp-schemas.mjs --out <file>       write (or, with --check, compare) another file
 *
 * `npm run dump:mcp-schemas` builds first and then runs this script.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { Client } from '@modelcontextprotocol/sdk/client/index.js';
import { InMemoryTransport } from '@modelcontextprotocol/sdk/inMemory.js';

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');

function parseArgs(argv) {
  const opts = { check: false, dist: resolve(repoRoot, 'dist'), out: resolve(repoRoot, 'docs', 'mcp-tool-schemas.json') };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === '--check') opts.check = true;
    else if (a === '--dist' && argv[i + 1] !== undefined) opts.dist = resolve(argv[++i]);
    else if (a === '--out' && argv[i + 1] !== undefined) opts.out = resolve(argv[++i]);
    else {
      process.stderr.write(`dump-mcp-schemas: unknown argument ${JSON.stringify(a)}\nusage: node scripts/dump-mcp-schemas.mjs [--check] [--dist <dir>] [--out <file>]\n`);
      process.exit(2);
    }
  }
  return opts;
}

/** Recursively sort object keys so the output does not depend on construction order. Arrays keep their order. */
function sortKeys(value) {
  if (Array.isArray(value)) return value.map(sortKeys);
  if (value !== null && typeof value === 'object') {
    const out = {};
    for (const key of Object.keys(value).sort()) out[key] = sortKeys(value[key]);
    return out;
  }
  return value;
}

async function build(dist) {
  for (const rel of ['mcp/server.js', 'sdk/gcr.js', 'version.js', 'mcp/aliases.js']) {
    if (!existsSync(resolve(dist, rel))) {
      process.stderr.write(`dump-mcp-schemas: ${resolve(dist, rel)} not found. Run "npm run build" first (or pass --dist <dir>).\n`);
      process.exit(2);
    }
  }
  const load = (rel) => import(pathToFileURL(resolve(dist, rel)).href);
  const [{ Gcr }, { createGcrMcpServer, SERVER_INSTRUCTIONS }, { TOOL_NAME, TOOL_VERSION }, { LEGACY_ALIASES }] = await Promise.all([
    load('sdk/gcr.js'),
    load('mcp/server.js'),
    load('version.js'),
    load('mcp/aliases.js'),
  ]);

  const gcr = Gcr.open({ dbPath: ':memory:', actor: 'mcp' });
  const server = createGcrMcpServer(gcr, { allowWrites: false, maxResultBytes: 200_000 });
  const [clientTransport, serverTransport] = InMemoryTransport.createLinkedPair();
  const client = new Client({ name: 'dump-mcp-schemas', version: '0.0.0' });
  try {
    await Promise.all([server.connect(serverTransport), client.connect(clientTransport)]);
    const { tools } = await client.listTools();
    return {
      $comment: 'Generated by scripts/dump-mcp-schemas.mjs from the running server (tools/list). Do not edit by hand: run "npm run dump:mcp-schemas".',
      server: {
        name: TOOL_NAME,
        version: TOOL_VERSION,
        capabilities: client.getServerCapabilities() ?? {},
        instructions: client.getInstructions() ?? SERVER_INSTRUCTIONS,
      },
      legacyAliases: LEGACY_ALIASES,
      tools: tools.map((t) => ({
        name: t.name,
        title: t.title ?? null,
        description: t.description ?? null,
        annotations: t.annotations ?? null,
        inputSchema: t.inputSchema,
        outputSchema: t.outputSchema ?? null,
      })),
    };
  } finally {
    await client.close();
    await server.close();
    gcr.close();
  }
}

const opts = parseArgs(process.argv.slice(2));
const text = `${JSON.stringify(sortKeys(await build(opts.dist)), null, 2)}\n`;

if (opts.check) {
  const current = existsSync(opts.out) ? readFileSync(opts.out, 'utf8') : null;
  if (current === text) {
    process.stdout.write(`dump-mcp-schemas: ${opts.out} is up to date\n`);
    process.exit(0);
  }
  process.stderr.write(`dump-mcp-schemas: ${opts.out} is ${current === null ? 'missing' : 'stale'}. Run "npm run dump:mcp-schemas" and commit the result.\n`);
  process.exit(1);
}

mkdirSync(dirname(opts.out), { recursive: true });
writeFileSync(opts.out, text);
process.stdout.write(`dump-mcp-schemas: wrote ${opts.out} (${text.length} bytes)\n`);
