#!/usr/bin/env node
// Generates docs/AUDIT_REPORT.md: the branch / model provenance audit of the COMMITTED SYNTHETIC FIXTURES
// (CODEX_TASK Phase 3: "Publish a non-sensitive ... branch/model provenance audit").
//
//   npm run audit:report                 rewrite docs/AUDIT_REPORT.md (needs dist/ from `npm run build`)
//   node scripts/audit-report.mjs --check   exit 1 if the committed file differs from what the product produces now
//   node scripts/audit-report.mjs --cli <main.js> --out <file>   use another build / another output file
//
// What it does: imports every file under fixtures/chatgpt and fixtures/claude into ONE temporary database with the BUILT
// `gcr import` (exactly what a user runs), runs `gcr audit` and `gcr stats --group-by model` as child processes and
// renders the counts. Deterministic: no clock, no hostname, no paths, an empty environment for the children. The
// temporary directory is removed at the end. Nothing here touches the network; the data is synthetic, so the report says
// nothing about any real export (a real export is exactly what has NOT been tested).
import { spawnSync } from 'node:child_process';
import { mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

function parseArgs(argv) {
  const opts = { cli: join(root, 'dist', 'cli', 'main.js'), out: join(root, 'docs', 'AUDIT_REPORT.md'), check: false };
  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i];
    if (arg === '--check') opts.check = true;
    else if (arg === '--cli' || arg === '--out') {
      const value = argv[++i];
      if (value === undefined) throw new Error(`${arg} needs a value`);
      opts[arg.slice(2)] = resolve(process.cwd(), value);
    } else throw new Error(`unknown argument: ${arg}`);
  }
  return opts;
}

function runCli(cli, args) {
  const r = spawnSync(process.execPath, [cli, ...args], {
    encoding: 'utf8',
    env: { PATH: process.env.PATH ?? '', LC_ALL: 'C' },
    stdio: ['ignore', 'pipe', 'pipe'],
    timeout: 120_000,
    maxBuffer: 64 * 1024 * 1024,
  });
  if (r.error !== undefined) throw r.error;
  if (r.status !== 0) throw new Error(`gcr ${args.join(' ')} failed (exit ${String(r.status)}): ${r.stderr}`);
  return r.stdout;
}

const fmt = (n) => (typeof n === 'number' ? n.toLocaleString('en-US') : String(n));
const pct = (a, b) => (b === 0 ? 'n/a' : `${((100 * a) / b).toFixed(1)}%`);

function render({ audit, models, files }) {
  const d = audit.data;
  const bp = d.branchProvenance;
  const mp = d.modelProvenance;
  const lines = [];
  lines.push('# Branch and model provenance audit (synthetic fixtures)');
  lines.push('');
  lines.push('Generated by `npm run audit:report` (`scripts/audit-report.mjs`) from the built `gcr audit` and `gcr stats --group-by model`. **Do not edit by hand**: re-run the script; `node scripts/audit-report.mjs --check` fails when this page is stale.');
  lines.push('');
  lines.push('> **What this is and is not.** Every number below describes the SYNTHETIC fixtures committed under `fixtures/chatgpt` and `fixtures/claude`, which were written to contain the awkward cases (cycles, missing parents, absent models, unknown roles, hidden messages, two providers). It shows what the audit reports on such data. It says NOTHING about the branch structure or model fields of a real ChatGPT or Claude export: no real export has been used, and an active branch or a model that a source does not state is reported as unknown, never inferred (FR-16, `docs/DECISIONS.md` ADR-0009).');
  lines.push('');
  lines.push('## Scope');
  lines.push('');
  lines.push(`* Fixture files imported: ${files.chatgpt} ChatGPT-shaped and ${files.claude} Claude-shaped (one \`gcr import\` each, same database).`);
  lines.push(`* Conversations scanned: ${fmt(d.scanned.conversations)}; messages scanned: ${fmt(d.scanned.messages)}.`);
  lines.push('');
  lines.push('## Branch provenance');
  lines.push('');
  if (bp === null || bp === undefined) {
    lines.push('Branch provenance was not computed (no tree-based check selected).');
  } else {
    lines.push('| Measure | Conversations |');
    lines.push('| --- | --- |');
    lines.push(`| With more than one branch | ${fmt(bp.conversationsWithMultipleBranches)} |`);
    lines.push(`| Largest number of branches in one conversation | ${fmt(bp.maxBranchesInOneConversation)} |`);
    lines.push(`| Active branch KNOWN (the source gave a valid active-branch pointer, \`current_node\` for ChatGPT) | ${fmt(bp.conversationsWithKnownActiveBranch)} (${pct(bp.conversationsWithKnownActiveBranch, d.scanned.conversations)}) |`);
    lines.push(`| Active branch UNKNOWN (pointer missing, invalid or unreachable; GCR does not guess) | ${fmt(bp.conversationsWithUnknownActiveBranch)} (${pct(bp.conversationsWithUnknownActiveBranch, d.scanned.conversations)}) |`);
  }
  lines.push('');
  lines.push('## Model provenance');
  lines.push('');
  if (mp === null || mp === undefined) {
    lines.push('Model provenance was not computed.');
  } else {
    const assistant = mp.assistantMessagesWithModel + mp.assistantMessagesWithoutModel;
    lines.push('| Measure | Value |');
    lines.push('| --- | --- |');
    lines.push(`| Assistant messages with an explicit model from the source | ${fmt(mp.assistantMessagesWithModel)} of ${fmt(assistant)} (${pct(mp.assistantMessagesWithModel, assistant)}) |`);
    lines.push(`| Assistant messages WITHOUT a model (kept as unknown) | ${fmt(mp.assistantMessagesWithoutModel)} (${pct(mp.assistantMessagesWithoutModel, assistant)}) |`);
    lines.push(`| Conversations with at least one explicit model | ${fmt(mp.conversationsWithAnyModel)} |`);
  }
  lines.push('');
  lines.push('Messages grouped by the model the source stated (`gcr stats --group-by model`; the unknown group is its own row, never merged into a model):');
  lines.push('');
  lines.push('| Model | Messages | Conversations |');
  lines.push('| --- | --- | --- |');
  for (const row of models.data.rows) lines.push(`| ${row.key === null ? '*unknown (not supplied by source)*' : `\`${row.key}\``} | ${fmt(row.messages)} | ${fmt(row.conversations)} |`);
  lines.push('');
  lines.push('## Findings by check');
  lines.push('');
  lines.push('| Check | Severity | Affected | Of | Notes |');
  lines.push('| --- | --- | --- | --- | --- |');
  for (const f of d.findings) {
    const by = f.byCode === undefined ? '' : Object.entries(f.byCode).map(([k, v]) => `\`${k}\` ${fmt(v)}`).join(', ');
    lines.push(`| ${f.check} | ${f.severity} | ${fmt(f.count)} | ${fmt(f.total)} | ${by} |`);
  }
  lines.push('');
  if (d.warnings.length > 0) {
    lines.push('## Warnings the audit itself reported');
    lines.push('');
    for (const w of d.warnings) lines.push(`* \`${w.code}\`: ${w.message}`);
    lines.push('');
  }
  lines.push('## Reproduce');
  lines.push('');
  lines.push('```bash');
  lines.push('npm run build');
  lines.push('for f in fixtures/chatgpt/*.json fixtures/claude/*.json; do node dist/cli/main.js import "$f" --db /tmp/audit.sqlite --quiet; done');
  lines.push('node dist/cli/main.js audit --db /tmp/audit.sqlite --format json');
  lines.push('node dist/cli/main.js stats --group-by model --db /tmp/audit.sqlite --format json');
  lines.push('```');
  lines.push('');
  return `${lines.join('\n')}`;
}

function main() {
  const opts = parseArgs(process.argv.slice(2));
  const work = mkdtempSync(join(tmpdir(), 'gcr-audit-report-'));
  try {
    const db = join(work, 'audit.sqlite');
    const files = { chatgpt: 0, claude: 0 };
    for (const provider of ['chatgpt', 'claude']) {
      const dir = join(root, 'fixtures', provider);
      for (const name of readdirSync(dir).filter((n) => n.endsWith('.json')).sort()) {
        runCli(opts.cli, ['import', join(dir, name), '--db', db, '--quiet', '--format', 'json']);
        files[provider]++;
      }
    }
    const audit = JSON.parse(runCli(opts.cli, ['audit', '--db', db, '--format', 'json']));
    const models = JSON.parse(runCli(opts.cli, ['stats', '--group-by', 'model', '--db', db, '--format', 'json']));
    const text = render({ audit, models, files });
    if (opts.check) {
      let current = '';
      try {
        current = readFileSync(opts.out, 'utf8');
      } catch {
        // a missing file is simply "stale"
      }
      if (current !== text) {
        process.stderr.write(`audit-report: ${opts.out} is stale; run: npm run audit:report\n`);
        process.exit(1);
      }
      process.stdout.write('audit-report: docs/AUDIT_REPORT.md is up to date\n');
      return;
    }
    writeFileSync(opts.out, text);
    process.stdout.write(`audit-report: wrote ${opts.out}\n`);
  } finally {
    rmSync(work, { recursive: true, force: true });
  }
}

main();
