#!/usr/bin/env node
// Captures the help text of the BUILT command-line interface into docs/CLI_HELP.txt (CODEX_TASK Phase 3, "CLI help capture").
//
//   npm run capture:cli-help                 build, then rewrite docs/CLI_HELP.txt
//   node scripts/capture-cli-help.mjs        same, without building (needs dist/ from `npm run build`)
//   node scripts/capture-cli-help.mjs --check   fail (exit 1) if docs/CLI_HELP.txt differs from what the CLI prints now
//   node scripts/capture-cli-help.mjs --cli <main.js> --out <file>   use another build / another output file
//
// What it does: runs `gcr --help` and `gcr [group] <command> --help` for every command as a CHILD PROCESS of the built
// executable (exactly what a user runs) and writes the outputs, in command-table order, into one text file. The list of
// commands is read from the build's own command table (<build>/commands/index.js), so a new command is captured
// without editing this script. The output is deterministic: no timestamps, no paths, no environment; the child runs
// with an empty environment (plus PATH), so nothing about the machine can leak into the file.
// Nothing here touches the network, a database or any conversation data.
import { spawnSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

function parseArgs(argv) {
  const opts = { cli: join(root, 'dist', 'cli', 'main.js'), out: join(root, 'docs', 'CLI_HELP.txt'), check: false };
  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i];
    if (arg === '--check') opts.check = true;
    else if (arg === '--cli' || arg === '--out') {
      const value = argv[++i];
      if (value === undefined) throw new Error(`${arg} needs a value`);
      opts[arg.slice(2)] = resolve(process.cwd(), value);
    } else throw new Error(`unknown argument: ${arg}`);
  }
  return opts;
}

function runCli(cli, args) {
  const r = spawnSync(process.execPath, [cli, ...args], {
    encoding: 'utf8',
    env: { PATH: process.env.PATH ?? '', LC_ALL: 'C' },
    stdio: ['ignore', 'pipe', 'pipe'],
    timeout: 30_000,
  });
  if (r.error !== undefined) throw r.error;
  if (r.status !== 0 || r.stderr !== '') {
    throw new Error(`gcr ${args.join(' ')} failed (exit ${String(r.status)}): ${r.stderr}`);
  }
  return r.stdout;
}

async function main() {
  const opts = parseArgs(process.argv.slice(2));
  const table = await import(pathToFileURL(join(dirname(opts.cli), 'commands', 'index.js')).href);
  const topLevel = table.TOP_LEVEL_NAMES.filter((name) => name !== 'help');

  /** [argv words, ...] in the order a reader meets them: the group page, then its subcommands. */
  const pages = [[]];
  for (const name of topLevel) {
    pages.push([name]);
    const group = table.findGroup(name);
    if (group !== undefined) for (const child of group.children) pages.push([...child.path]);
  }

  const version = runCli(opts.cli, ['--version']).trim();
  const bar = '='.repeat(80);
  const parts = [
    `GCR command-line help, captured from the built CLI (${version}).`,
    'Generated by scripts/capture-cli-help.mjs - do not edit by hand. Regenerate with: npm run capture:cli-help',
    'Every example uses synthetic ids; nothing here comes from a real export.',
    '',
  ];
  for (const words of pages) {
    const title = `$ gcr ${[...words, '--help'].join(' ')}`;
    parts.push(bar, title, bar, runCli(opts.cli, [...words, '--help']).replace(/\n+$/, ''), '');
  }
  const text = `${parts.join('\n')}\n`;

  if (opts.check) {
    let current = '';
    try {
      current = readFileSync(opts.out, 'utf8');
    } catch {
      // a missing file is reported below as "differs"
    }
    if (current !== text) {
      process.stderr.write(`${opts.out} is out of date. Run: npm run capture:cli-help\n`);
      process.exit(1);
    }
    process.stdout.write(`${opts.out} is up to date (${pages.length} pages).\n`);
    return;
  }
  writeFileSync(opts.out, text);
  process.stdout.write(`wrote ${opts.out} (${pages.length} pages, ${text.length} characters)\n`);
}

main().catch((e) => {
  process.stderr.write(`capture-cli-help: ${e instanceof Error ? e.message : String(e)}\n`);
  process.exit(1);
});
